    private static void AppendSceneMethod
    (
        StringBuilder      sb,
        CustomizationDraft draft,
        DraftExportContext context
    )
    {
        if (!context.HasScene)
            return;

        Line(sb, 1, "public override void CustomizeScene(SceneExtractor scene)");
        Line(sb, 1, "{");

        foreach (var removal in draft.MeshRemovals.Where(static x => x.Enabled && !string.IsNullOrWhiteSpace(x.MeshKey)))
        {
            AppendNoteComment(sb, 2, removal.Note);
            Line(sb, 2, $"scene.Meshes.Remove(\"{Escape(removal.MeshKey)}\");");
        }

        AppendMeshPatchGroups(sb, draft);

        foreach (var insertion in draft.InstancePatches.Where(static x => IsValidInstancePatch(x) && x.Kind == DraftSceneInstancePatchKind.Insert))
            AppendInstanceInsertion(sb, insertion);

        foreach (var insertion in draft.ColliderInsertions.Where(static x => x.Enabled))
            AppendColliderInsertion(sb, insertion);

        Line(sb, 1, "}");
        Line(sb);
    }

    private static void AppendMeshPatchGroups
    (
        StringBuilder      sb,
        CustomizationDraft draft
    )
    {
        var meshKeys = draft.PartPatches
                            .Where(IsValidPartPatch)
                            .Select(static x => x.MeshKey)
                            .Concat
                            (
                                draft.InstancePatches
                                     .Where(static x => IsValidInstancePatch(x) && x.Kind != DraftSceneInstancePatchKind.Insert)
                                     .Select(static x => x.MeshKey)
                            )
                            .Distinct(StringComparer.Ordinal);

        var meshIndex = 0;

        foreach (var meshKey in meshKeys)
        {
            var meshVariable = $"mesh{meshIndex++}";
            var partPatches = draft.PartPatches
                                   .Where(x => IsValidPartPatch(x) && string.Equals(x.MeshKey, meshKey, StringComparison.Ordinal))
                                   .ToArray();
            var instancePatches = draft.InstancePatches
                                       .Where(x => IsValidInstancePatch(x) &&
                                                   x.Kind != DraftSceneInstancePatchKind.Insert &&
                                                   string.Equals(x.MeshKey, meshKey, StringComparison.Ordinal))
                                       .ToArray();

            Line(sb, 2, $"if (scene.Meshes.TryGetValue(\"{Escape(meshKey)}\", out var {meshVariable}))");
            Line(sb, 2, "{");

            foreach (var patch in partPatches)
                AppendPartPatch(sb, patch, meshVariable, 3);

            for (var i = 0; i < instancePatches.Length; ++i)
                AppendInstancePatch(sb, instancePatches[i], meshVariable, i, 3);

            Line(sb, 2, "}");
        }
    }

    private static bool IsValidPartPatch
    (
        DraftScenePartPatch patch
    ) =>
        patch.Enabled                             &&
        !string.IsNullOrWhiteSpace(patch.MeshKey) &&
        patch.PartIndex >= 0                      &&
        patch.Kind switch
        {
            DraftScenePartPatchKind.Vertex         => patch.VertexIndex    >= 0,
            DraftScenePartPatchKind.PrimitiveFlags => patch.PrimitiveIndex >= 0,
            DraftScenePartPatchKind.PrimitiveEdit  => patch.PrimitiveIndex >= 0,
            _                                      => false
        };

    private static bool IsValidInstancePatch
    (
        DraftSceneInstancePatch patch
    ) =>
        patch.Enabled                             &&
        !string.IsNullOrWhiteSpace(patch.MeshKey) &&
        patch.Kind switch
        {
            DraftSceneInstancePatchKind.ClearInstances => true,
            DraftSceneInstancePatchKind.RemoveInstance => patch.InstanceId != 0 || patch.InstanceIndex >= 0,
            DraftSceneInstancePatchKind.Transform      => patch.InstanceId != 0 || patch.InstanceIndex >= 0,
            DraftSceneInstancePatchKind.Insert         => true,
            DraftSceneInstancePatchKind.SetFlags => (patch.InstanceId != 0 || patch.InstanceIndex >= 0) &&
                                                    (patch.ForceSetPrimFlags   != PrimitiveFlags.None ||
                                                     patch.ForceClearPrimFlags != PrimitiveFlags.None),
            _ => false
        };

    private static void AppendSettingsMethod
    (
        StringBuilder      sb,
        CustomizationDraft draft
    )
    {
        var links = draft.OffMeshConnections.Where(static x => x.Enabled).ToArray();
        if (links.Length == 0)
            return;

        Line(sb, 1, "public override void CustomizeSettings(DtNavMeshCreateParams config)");
        Line(sb, 1, "{");

        foreach (var link in links)
        {
            var area             = FormatEnum(link.Area, "NavmeshArea");
            var flags            = FormatNavmeshPolyFlags(link.Flags);
            var kind             = FormatEnum(link.Kind, "NavmeshOffMeshKind");
            var traversalProfile = FormatTraversalProfile(link.TraversalProfile);

            AppendNoteComment(sb, 2, link.Note);
            Line(sb, 2, "config.AddOffMeshConnection");
            Line(sb, 2, "(");
            Line(sb, 3, $"{FormatVector(link.Start)},");
            Line(sb, 3, $"{FormatVector(link.End)},");
            Line(sb, 3, $"{FormatFloat(link.Radius)},");
            Line(sb, 3, $"{FormatBool(link.Bidirectional)},");
            Line(sb, 3, $"{FormatInt(link.UserId)},");
            Line(sb, 3, $"{area},");
            Line(sb, 3, $"{flags},");
            Line(sb, 3, $"{kind},");
            Line(sb, 3, traversalProfile);
            Line(sb, 2, ");");
        }

        Line(sb, 1, "}");
        Line(sb);
    }

    private static void AppendMeshMethod
    (
        StringBuilder      sb,
        CustomizationDraft draft
    )
    {
        var links = draft.MeshLinks.Where(static x => x.Enabled).ToArray();
        if (links.Length == 0)
            return;

        Line(sb, 1, "public override void CustomizeMesh(Navmesh mesh, List<uint> festivalLayers)");
        Line(sb, 1, "{");

        foreach (var link in links)
        {
            var call = link.Kind switch
            {
                DraftMeshLinkKind.Points     => "LinkPoints",
                DraftMeshLinkKind.Shortcut   => "LinkShortcut",
                DraftMeshLinkKind.ClientPath => "LinkClientPath",
                _                            => "LinkPoints"
            };
            var traversalProfile = FormatTraversalProfile(link.TraversalProfile);
            AppendNoteComment(sb, 2, link.Note);
            Line
            (
                sb,
                2,
                $"{call}(mesh, {FormatVector(link.Start)}, {FormatVector(link.End)}, {FormatBool(link.Bidirectional)}, {traversalProfile});"
            );
        }

        Line(sb, 1, "}");
        Line(sb);
    }

    private static void AppendPartPatch
    (
        StringBuilder       sb,
        DraftScenePartPatch patch,
        string              meshVariable,
        int                 indent
    )
    {
        AppendNoteComment(sb, indent, patch.Note);
        Line(sb, indent,     $"if ({patch.PartIndex} < {meshVariable}.Parts.Count)");
        Line(sb, indent,     "{");
        Line(sb, indent + 1, $"var part = {meshVariable}.Parts[{patch.PartIndex}];");

        switch (patch.Kind)
        {
            case DraftScenePartPatchKind.Vertex:
                Line(sb, indent + 1, $"if ({patch.VertexIndex} < part.Vertices.Count)");
                Line(sb, indent + 1, "{");
                Line(sb, indent + 2, $"part.Vertices[{patch.VertexIndex}] = {FormatVector(patch.Position)};");
                Line(sb, indent + 2, "part.LocalBounds = CalculateLocalBounds(part.Vertices);");
                Line(sb, indent + 2, $"RecalculateMeshBounds({meshVariable});");
                Line(sb, indent + 1, "}");
                break;
            case DraftScenePartPatchKind.PrimitiveFlags:
                Line(sb, indent + 1, $"if ({patch.PrimitiveIndex} < part.Primitives.Count)");
                Line(sb, indent + 1, "{");
                Line(sb, indent + 2, $"var primitive = part.Primitives[{patch.PrimitiveIndex}];");
                Line(sb, indent + 2, $"primitive.Flags = {FormatPrimitiveFlags(patch.Flags)};");
                Line(sb, indent + 2, $"part.Primitives[{patch.PrimitiveIndex}] = primitive;");
                Line(sb, indent + 1, "}");
                break;
            case DraftScenePartPatchKind.PrimitiveEdit:
                Line(sb, indent + 1, $"if ({patch.PrimitiveIndex} < part.Primitives.Count)");
                Line(sb, indent + 1, "{");
                Line
                (
                    sb,
                    indent + 2,
                    $"part.Primitives[{patch.PrimitiveIndex}] = new({patch.V1}, {patch.V2}, {patch.V3}, {FormatPrimitiveFlags(patch.Flags)}, {FormatUlong(patch.Material)});"
                );
                Line(sb, indent + 1, "}");
                break;
        }

        Line(sb, indent, "}");
    }

    private static void AppendInstancePatch
    (
        StringBuilder           sb,
        DraftSceneInstancePatch patch,
        string                  meshVariable,
        int                     patchIndex,
        int                     indent
    )
    {
        AppendNoteComment(sb, indent, patch.Note);

        switch (patch.Kind)
        {
            case DraftSceneInstancePatchKind.ClearInstances:
                Line(sb, indent, $"{meshVariable}.Instances.Clear();");
                break;
            case DraftSceneInstancePatchKind.RemoveInstance:
                Line(sb, indent,     "{");
                Line(sb, indent + 1, $"var index = ResolveInstanceIndex({meshVariable}, {FormatUlong(patch.InstanceId)}, {patch.InstanceIndex});");
                Line(sb, indent + 1, "if (index >= 0)");
                Line(sb, indent + 2, $"{meshVariable}.Instances.RemoveAt(index);");
                Line(sb, indent,     "}");
                break;
            case DraftSceneInstancePatchKind.Transform:
                var transformInstance = $"instance{patchIndex}";
                Line(sb, indent, $"if (ResolveInstance({meshVariable}, {FormatUlong(patch.InstanceId)}, {patch.InstanceIndex}) is {{ }} {transformInstance})");
                Line(sb, indent, "{");
                AppendMatrixAssignment(sb, indent + 1, $"{transformInstance}.WorldTransform", patch.WorldTransform);
                Line(sb, indent + 1, $"{transformInstance}.WorldBounds = TransformBounds({transformInstance}.WorldTransform, {meshVariable}.LocalBounds);");
                Line(sb, indent, "}");
                break;
            case DraftSceneInstancePatchKind.SetFlags:
                var flagsInstance = $"instance{patchIndex}";
                Line(sb, indent,     $"if (ResolveInstance({meshVariable}, {FormatUlong(patch.InstanceId)}, {patch.InstanceIndex}) is {{ }} {flagsInstance})");
                Line(sb, indent,     "{");
                Line(sb, indent + 1, $"{flagsInstance}.ForceSetPrimFlags = {FormatPrimitiveFlags(patch.ForceSetPrimFlags)};");
                Line(sb, indent + 1, $"{flagsInstance}.ForceClearPrimFlags = {FormatPrimitiveFlags(patch.ForceClearPrimFlags)};");
                Line(sb, indent,     "}");
                break;
        }
    }

    private static void AppendInstanceInsertion
    (
        StringBuilder           sb,
        DraftSceneInstancePatch insertion
    )
    {
        AppendNoteComment(sb, 2, insertion.Note);
        Line(sb, 2, "scene.InsertMeshInstances");
        Line(sb, 2, "(");
        Line(sb, 3, $"\"{Escape(insertion.MeshKey)}\",");
        Line(sb, 3, "new Matrix4x3");
        Line(sb, 3, "{");
        Line(sb, 4, $"Row0 = {FormatVector(insertion.WorldTransform.Row0)},");
        Line(sb, 4, $"Row1 = {FormatVector(insertion.WorldTransform.Row1)},");
        Line(sb, 4, $"Row2 = {FormatVector(insertion.WorldTransform.Row2)},");
        Line(sb, 4, $"Row3 = {FormatVector(insertion.WorldTransform.Row3)}");
        Line(sb, 3, "},");
        Line(sb, 3, $"{Math.Clamp(insertion.Count, 1, 1024)},");
        Line(sb, 3, $"{FormatVector(insertion.Offset)},");
        Line(sb, 3, $"{FormatUlong(insertion.Material)},");
        Line(sb, 3, $"{FormatPrimitiveFlags(insertion.ForceSetPrimFlags)},");
        Line(sb, 3, FormatPrimitiveFlags(insertion.ForceClearPrimFlags));
        Line(sb, 2, ");");
    }

    private static void AppendColliderInsertion
    (
        StringBuilder               sb,
        DraftSceneColliderInsertion insertion
    )
    {
        var min = Vector3.Min(insertion.Min, insertion.Max);
        var max = Vector3.Max(insertion.Min, insertion.Max);
        var forceSetFlags   = FormatPrimitiveFlags(insertion.ForceSetPrimFlags);
        var forceClearFlags = FormatPrimitiveFlags(insertion.ForceClearPrimFlags);

        AppendNoteComment(sb, 2, insertion.Note);

        if (insertion.Kind == DraftSceneColliderInsertionKind.OrientedCylinder)
        {
            Line(sb, 2, "scene.InsertOrientedCylinderCollider");
            Line(sb, 2, "(");
            Line(sb, 3, $"{FormatVector(insertion.Start)},");
            Line(sb, 3, $"{FormatVector(insertion.End)},");
            Line(sb, 3, $"{FormatFloat(MathF.Max(MathF.Abs(insertion.Radius), 0.005f))},");
            Line(sb, 3, $"{forceSetFlags},");
            Line(sb, 3, forceClearFlags);
            Line(sb, 2, ");");
            return;
        }

        if (insertion.Kind is DraftSceneColliderInsertionKind.OrientedBox or DraftSceneColliderInsertionKind.Ramp)
        {
            var orientedCall = insertion.Kind == DraftSceneColliderInsertionKind.Ramp ?
                                   "InsertRampCollider" :
                                   "InsertOrientedBoxCollider";
            Line(sb, 2, $"scene.{orientedCall}");
            Line(sb, 2, "(");
            Line(sb, 3, $"{FormatVector((max - min) * 0.5f)},");
            Line(sb, 3, $"{FormatVector((min + max) * 0.5f)},");
            Line(sb, 3, $"{FormatFloat(insertion.RotationDegrees)},");
            Line(sb, 3, $"{forceSetFlags},");
            Line(sb, 3, forceClearFlags);
            Line(sb, 2, ");");
            return;
        }

        if (insertion.Kind == DraftSceneColliderInsertionKind.Wall)
        {
            var halfExtents = (max - min) * 0.5f;
            Line(sb, 2, "scene.InsertWallCollider");
            Line(sb, 2, "(");
            Line(sb, 3, $"new({FormatFloat(halfExtents.X)}, {FormatFloat(halfExtents.Y)}),");
            Line(sb, 3, $"{FormatVector((min + max) * 0.5f)},");
            Line(sb, 3, $"{FormatFloat(insertion.RotationDegrees)},");
            Line(sb, 3, $"{FormatBool(insertion.DoubleSided)},");
            Line(sb, 3, $"{forceSetFlags},");
            Line(sb, 3, forceClearFlags);
            Line(sb, 2, ");");
            return;
        }

        if (insertion.Kind == DraftSceneColliderInsertionKind.WalkableFloor)
        {
            var halfExtents = (max - min) * 0.5f;
            Line(sb, 2, "scene.InsertWalkableFloor");
            Line(sb, 2, "(");
            Line(sb, 3, $"new({FormatFloat(halfExtents.X)}, {FormatFloat(halfExtents.Z)}),");
            Line(sb, 3, $"{FormatVector((min + max) * 0.5f)},");
            Line(sb, 3, $"{FormatFloat(insertion.RotationDegrees)},");
            Line(sb, 3, $"{forceSetFlags},");
            Line(sb, 3, forceClearFlags);
            Line(sb, 2, ");");
            return;
        }

        if (insertion.Kind is DraftSceneColliderInsertionKind.RemoveInstances or DraftSceneColliderInsertionKind.SetInstanceFlags)
        {
            var volumeCall = insertion.Kind == DraftSceneColliderInsertionKind.RemoveInstances ?
                                 "RemoveMeshInstancesInBounds" :
                                 "SetMeshInstanceFlagsInBounds";
            Line(sb, 2, $"scene.{volumeCall}");
            Line(sb, 2, "(");
            Line(sb, 3, "new AABB");
            Line(sb, 3, "{");
            Line(sb, 4, $"Min = {FormatVector(min)},");
            Line(sb, 4, $"Max = {FormatVector(max)}");
            Line(sb, 3, "},");
            if (insertion.Kind == DraftSceneColliderInsertionKind.SetInstanceFlags)
            {
                Line(sb, 3, $"{forceSetFlags},");
                Line(sb, 3, $"{forceClearFlags},");
            }

            Line(sb, 3, $"\"{Escape(insertion.MeshKeyContains)}\"");
            Line(sb, 2, ");");
            return;
        }

        var call = insertion.Kind switch
        {
            DraftSceneColliderInsertionKind.Cylinder => "InsertCylinderCollider",
            DraftSceneColliderInsertionKind.Sphere   => "InsertSphereCollider",
            _                                        => "InsertAABoxCollider"
        };

        Line(sb, 2, "scene." + call);
        Line(sb, 2, "(");
        Line(sb, 3, "new AABB");
        Line(sb, 3, "{");
        Line(sb, 4, $"Min = {FormatVector(min)},");
        Line(sb, 4, $"Max = {FormatVector(max)}");

        if (insertion is { ForceSetPrimFlags: PrimitiveFlags.None, ForceClearPrimFlags: PrimitiveFlags.None })
            Line(sb, 3, "}");
        else
        {
            Line(sb, 3, "},");
            Line
            (
                sb,
                3,
                insertion.ForceClearPrimFlags == PrimitiveFlags.None ?
                    forceSetFlags :
                    $"{forceSetFlags},"
            );
            if (insertion.ForceClearPrimFlags != PrimitiveFlags.None)
                Line(sb, 3, forceClearFlags);
        }

        Line(sb, 2, ");");
    }

