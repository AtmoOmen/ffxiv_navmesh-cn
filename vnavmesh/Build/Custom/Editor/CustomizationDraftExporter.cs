    private static string BuildClassName
    (
        CustomizationDraft draft
    )
    {
        var suffix = SanitizeIdentifier(draft.TerritoryName);
        if (suffix.Length == 0)
            suffix = "Territory";

        return $"Z{draft.TerritoryID:D4}{suffix}EditorDraft";
    }

    private static string SanitizeIdentifier
    (
        string value
    )
    {
        var sb             = new StringBuilder(value.Length);
        var capitalizeNext = true;

        foreach (var ch in value)
        {
            switch (ch)
            {
                case >= 'a' and <= 'z':
                    sb.Append
                    (
                        capitalizeNext ?
                            char.ToUpperInvariant(ch) :
                            ch
                    );
                    capitalizeNext = false;
                    break;
                case >= 'A' and <= 'Z' or >= '0' and <= '9':
                    sb.Append(ch);
                    capitalizeNext = false;
                    break;
                default:
                    capitalizeNext = true;
                    break;
            }
        }

        return sb.ToString();
    }

    private static string FormatFloat
    (
        float value
    )
    {
        if (float.IsNaN(value))
            return "float.NaN";
        if (float.IsPositiveInfinity(value))
            return "float.PositiveInfinity";
        if (float.IsNegativeInfinity(value))
            return "float.NegativeInfinity";

        return value.ToString("R", CultureInfo.InvariantCulture) + "f";
    }

