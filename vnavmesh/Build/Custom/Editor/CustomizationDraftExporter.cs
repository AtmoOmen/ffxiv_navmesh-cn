    private static void AppendHelpers
    (
        StringBuilder      sb,
        DraftExportContext context
    )
    {
        if (context.NeedsInstanceHelpers)
        {
            Line(sb, 1, "private static MeshInstance? ResolveInstance(Mesh mesh, ulong instanceId, int instanceIndex)");
            Line(sb, 1, "{");
            Line(sb, 2, "var index = ResolveInstanceIndex(mesh, instanceId, instanceIndex);");
            Line(sb, 2, "return index >= 0 ? mesh.Instances[index] : null;");
            Line(sb, 1, "}");
            Line(sb);

            Line(sb, 1, "private static int ResolveInstanceIndex(Mesh mesh, ulong instanceId, int instanceIndex)");
            Line(sb, 1, "{");
            Line(sb, 2, "if (instanceIndex >= 0 && instanceIndex < mesh.Instances.Count && (instanceId == 0 || mesh.Instances[instanceIndex].Id == instanceId))");
            Line(sb, 3, "return instanceIndex;");
            Line(sb);
            Line(sb, 2, "if (instanceId != 0)");
            Line(sb, 2, "{");
            Line(sb, 3, "for (var i = 0; i < mesh.Instances.Count; ++i)");
            Line(sb, 3, "{");
            Line(sb, 4, "if (mesh.Instances[i].Id == instanceId)");
            Line(sb, 5, "return i;");
            Line(sb, 3, "}");
            Line(sb, 2, "}");
            Line(sb);
            Line(sb, 2, "return -1;");
            Line(sb, 1, "}");
            Line(sb);
        }

        if (context.NeedsLocalBoundsHelpers)
        {
            Line(sb, 1, "private static void RecalculateMeshBounds(Mesh mesh)");
            Line(sb, 1, "{");
            Line(sb, 2, "mesh.LocalBounds = CalculateLocalBounds(mesh.Parts);");
            Line(sb, 2, "foreach (var instance in mesh.Instances)");
            Line(sb, 3, "instance.WorldBounds = TransformBounds(instance.WorldTransform, mesh.LocalBounds);");
            Line(sb, 1, "}");
            Line(sb);

            Line(sb, 1, "private static AABB CalculateLocalBounds(List<MeshPart> parts)");
            Line(sb, 1, "{");
            Line(sb, 2, "var bounds = new AABB { Min = new(float.MaxValue), Max = new(float.MinValue) };");
            Line(sb, 2, "foreach (var part in parts)");
            Line(sb, 2, "{");
            Line(sb, 3, "bounds.Min = Vector3.Min(bounds.Min, part.LocalBounds.Min);");
            Line(sb, 3, "bounds.Max = Vector3.Max(bounds.Max, part.LocalBounds.Max);");
            Line(sb, 2, "}");
            Line(sb, 2, "return bounds;");
            Line(sb, 1, "}");
            Line(sb);

            Line(sb, 1, "private static AABB CalculateLocalBounds(List<Vector3> vertices)");
            Line(sb, 1, "{");
            Line(sb, 2, "var bounds = new AABB { Min = new(float.MaxValue), Max = new(float.MinValue) };");
            Line(sb, 2, "foreach (var vertex in vertices)");
            Line(sb, 2, "{");
            Line(sb, 3, "bounds.Min = Vector3.Min(bounds.Min, vertex);");
            Line(sb, 3, "bounds.Max = Vector3.Max(bounds.Max, vertex);");
            Line(sb, 2, "}");
            Line(sb, 2, "return bounds;");
            Line(sb, 1, "}");
            Line(sb);
        }

        if (!context.NeedsTransformBoundsHelper)
            return;

        Line(sb, 1, "private static AABB TransformBounds(Matrix4x3 worldTransform, AABB localBounds)");
        Line(sb, 1, "{");
        Line(sb, 2, "var localCenter = (localBounds.Min + localBounds.Max) * 0.5f;");
        Line(sb, 2, "var localExtent = (localBounds.Max - localBounds.Min) * 0.5f;");
        Line(sb, 2, "var axisX = worldTransform.Row0;");
        Line(sb, 2, "var axisY = worldTransform.Row1;");
        Line(sb, 2, "var axisZ = worldTransform.Row2;");
        Line(sb, 2, "var center = axisX * localCenter.X + axisY * localCenter.Y + axisZ * localCenter.Z + worldTransform.Row3;");
        Line(sb, 2, "var extent = Abs(axisX) * localExtent.X + Abs(axisY) * localExtent.Y + Abs(axisZ) * localExtent.Z;");
        Line(sb, 2, "return new() { Min = center - extent, Max = center + extent };");
        Line(sb, 1, "}");
        Line(sb);

        Line(sb, 1, "private static Vector3 Abs(Vector3 value) => new(MathF.Abs(value.X), MathF.Abs(value.Y), MathF.Abs(value.Z));");
        Line(sb);
    }

