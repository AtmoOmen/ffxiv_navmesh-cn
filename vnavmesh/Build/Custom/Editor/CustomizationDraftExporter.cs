    private static string FormatEnum<T>
    (
        T      value,
        string prefix
    ) where T : struct, Enum =>
        Enum.IsDefined(typeof(T), value) ?
            $"{prefix}.{value}" :
            $"({prefix}){Convert.ToInt64(value, CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture)}";

    private static string FormatFlags<T>
    (
        T      value,
        string prefix
    ) where T : struct, Enum
    {
        var raw = Convert.ToInt64(value, CultureInfo.InvariantCulture);
        if (raw == 0)
            return $"{prefix}.None";

        var          combined = 0L;
        List<string> parts    = [];

        foreach (var flag in Enum.GetValues<T>())
        {
            var current = Convert.ToInt64(flag, CultureInfo.InvariantCulture);
            if (current == 0 || (raw & current) != current)
                continue;

            combined |= current;
            parts.Add($"{prefix}.{flag}");
        }

        return combined == raw && parts.Count > 0 ?
                   string.Join(" | ", parts) :
                   $"({prefix}){raw.ToString(CultureInfo.InvariantCulture)}";
    }

    private static string Escape
    (
        string value
    ) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);

    private static string NormalizeLineEndings
    (
        string value
    ) =>
        value.Replace("\r\n", "\n", StringComparison.Ordinal).Replace("\r", "\n", StringComparison.Ordinal);

    private static void AppendNoteComment
    (
        StringBuilder sb,
        int           indent,
        string?       note
    )
    {
        if (string.IsNullOrWhiteSpace(note))
            return;

        foreach (var line in NormalizeLineEndings(note).Split('\n'))
        {
            var trimmed = line.Trim();
            if (trimmed.Length == 0)
                continue;

            Line(sb, indent, $"// {trimmed}");
        }
    }

    private static void Line
    (
        StringBuilder sb,
        int           indent = 0,
        string        text   = ""
    )
    {
        if (text.Length > 0)
            sb.Append(' ', indent * 4).Append(text);
        sb.Append('\n');
    }
